const DIALECT_PROJECTS: Record<string, string> = {
  sqlite: 'Providers/Sqlite/MigrateSqlite.csproj',
  postgres: 'Providers/Postgres/MigratePostgres.csproj',
  mysql: 'Providers/Mysql/MigrateMysql.csproj',
  sqlserver: 'Providers/SqlServer/MigrateSqlServer.csproj',
  oracle: 'Providers/Oracle/MigrateOracle.csproj',
};

export const cargoDefaultFeaturesLine = (dialects: string[]): string =>
  `default = [${dialects.map((name) => `"${name}"`).join(', ')}]`;

export const setCargoDefaultFeatures = (cargoToml: string, dialects: string[]): string => {
  const replacement = cargoDefaultFeaturesLine(dialects);
  const lines = cargoToml.split('\n');
  let replaced = false;
  const out = lines.map((line) => {
    if (!replaced && line.trimStart().startsWith('default = [')) {
      replaced = true;
      const indent = line.slice(0, line.length - line.trimStart().length);
      return `${indent}${replacement}`;
    }
    return line;
  });
  if (!replaced) {
    throw new Error('Cargo.toml is missing a features default = [...] line');
  }
  return out.join('\n');
};

export const rustDialectCrate = (dialect: string): string => `migraters-${dialect}`;

export const rustDialectIdent = (dialect: string): string =>
  rustDialectCrate(dialect).replaceAll('-', '_');

export const rustDialectPath = (dialect: string): string => `dialects/${dialect}`;

export const renderAttachedDialects = (dialects: string[]): string =>
  [
    '// Generated by migrate-init. Do not edit.',
    '#![allow(unused_imports)]',
    ...dialects.map((name) => `use ${rustDialectIdent(name)} as _;`),
    '',
  ].join('\n');

export const setCargoDialectDeps = (cargoToml: string, dialects: string[]): string => {
  const marker = '# migrate-init-dialects';
  const lines = dialects.map(
    (name) => `${rustDialectCrate(name)} = { path = "${rustDialectPath(name)}" }`,
  );
  const block = [`${marker}-start`, ...lines, `${marker}-end`].join('\n');
  if (cargoToml.includes(`${marker}-start`)) {
    return cargoToml.replace(
      new RegExp(`${marker}-start[\\s\\S]*?${marker}-end`),
      block,
    );
  }
  if (!cargoToml.includes('[dependencies]')) {
    throw new Error('Cargo.toml is missing [dependencies]');
  }
  return cargoToml.replace('[dependencies]', `[dependencies]\n${block}`);
};

export const renderDialectsProps = (dialects: string[]): string => {
  const refs = dialects
    .map((name) => DIALECT_PROJECTS[name])
    .filter((path): path is string => Boolean(path))
    .map((path) => `    <ProjectReference Include="$(MSBuildThisFileDirectory)${path}" />`);
  return ['<Project>', '  <ItemGroup>', ...refs, '  </ItemGroup>', '</Project>', ''].join('\n');
};
