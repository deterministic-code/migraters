#!/usr/bin/env node
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { spawnSync } from 'node:child_process';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const language = process.argv[2];

const npmCmd = process.platform === 'win32' ? 'npm.cmd' : 'npm';

const requireStatus = (result) => {
  if ((result.status ?? 1) !== 0) process.exit(result.status ?? 1);
};

const writeConfig = (lang, dialects, binDir) => {
  const lines = [`language: ${lang}`, 'dialects:'];
  if (dialects.length === 0) {
    lines[1] = 'dialects: []';
  } else {
    for (const name of dialects) lines.push(`  - ${name}`);
  }
  lines.push(`binDir: ${binDir}`, '');
  writeFileSync(join(root, '.migraters.yaml'), lines.join('\n'));
};

if (language === 'typescript') {
  const tsRoot = join(root, 'typescript');
  if (!existsSync(join(tsRoot, 'node_modules', 'better-sqlite3'))) {
    requireStatus(
      spawnSync(
        npmCmd,
        ['install', '--no-save', '--no-audit', '--no-fund', '--loglevel=error', 'better-sqlite3'],
        { cwd: tsRoot, stdio: 'inherit' },
      ),
    );
  }
  writeConfig('typescript', ['sqlite'], 'typescript/dist/src/bin');
  process.exit(0);
}

if (language === 'rust-core') {
  const cargoPath = join(root, 'rust', 'Cargo.toml');
  const raw = readFileSync(cargoPath, 'utf8');
  const block = '# migrate-init-dialects-start\n# migrate-init-dialects-end';
  const next = raw.includes('# migrate-init-dialects-start')
    ? raw.replace(/# migrate-init-dialects-start[\s\S]*?# migrate-init-dialects-end/, block)
    : raw.replace('[dependencies]', `[dependencies]\n${block}`);
  if (next !== raw) writeFileSync(cargoPath, next);
  writeFileSync(
    join(root, 'rust', 'src', 'attached_dialects.rs'),
    '// Generated by migrate-init. Do not edit.\n#![allow(unused_imports)]\n',
  );
  writeConfig('rust', [], 'rust/target/debug');
  process.exit(0);
}

if (language === 'csharp') {
  writeFileSync(
    join(root, 'csharp', 'dialects.props'),
    [
      '<Project>',
      '  <ItemGroup>',
      '    <ProjectReference Include="$(MSBuildThisFileDirectory)Dialects/Sqlite/MigrateSqlite.csproj" />',
      '  </ItemGroup>',
      '</Project>',
      '',
    ].join('\n'),
  );
  writeConfig('csharp', ['sqlite'], 'csharp/bin/Debug/net9.0');
  process.exit(0);
}

process.stderr.write('attach-sqlite: pass typescript, rust-core, or csharp\n');
process.exit(1);
